// ========================================
// STRATIFY AI — Proposals Page
// ========================================

const ProposalsPage = (() => {
  async function render(container, params) {
    if (params?.id) {
      await renderProposalDetail(container, params.id);
    } else {
      await renderProposalList(container);
    }
  }

  async function renderProposalList(container) {
    const allProjects = await Store.getProjects();
    const projects = allProjects.filter(p => p.proposal);

    container.innerHTML = `
      <div class="page-header">
        <div class="page-header-top">
          <div>
            <h1 class="page-title">Proposals</h1>
            <p class="page-subtitle">Client-ready proposals generated by the Pre-Sales Consultant Agent</p>
          </div>
        </div>
      </div>

      ${projects.length > 0 ? `
        <div class="stagger-children" style="display: flex; flex-direction: column; gap: var(--space-4);">
          ${projects.map(p => renderProposalCard(p)).join('')}
        </div>
      ` : `
        <div class="glass-card-static empty-state">
          <div class="empty-state-icon">📄</div>
          <h3 class="empty-state-title">No Proposals Yet</h3>
          <p class="empty-state-text">Create a new project to automatically generate a professional proposal via the agent pipeline.</p>
          <button class="btn btn-primary" onclick="Router.navigate('new-project')">➕ New Project</button>
        </div>
      `}
    `;
  }

  function renderProposalCard(project) {
    const proposal = project.proposal;
    const statusColors = {
      draft: 'badge-neutral',
      sent: 'badge-warning',
      accepted: 'badge-success',
      rejected: 'badge-danger',
    };

    return `
      <div class="glass-card" style="padding: var(--space-5); cursor: pointer;"
           onclick="Router.navigate('proposals/${project.id}')">
        <div style="display: flex; align-items: flex-start; justify-content: space-between; margin-bottom: var(--space-3);">
          <div>
            <h4 style="margin-bottom: var(--space-1);">${project.company || project.clientName}</h4>
            <p class="text-secondary" style="font-size: var(--text-sm);">
              ${project.clientName} · ${formatTimeAgo(proposal.generatedAt || project.createdAt)}
            </p>
          </div>
          <span class="badge ${statusColors[proposal.status] || 'badge-neutral'}">${capitalizeFirst(proposal.status || 'draft')}</span>
        </div>
        <p style="font-size: var(--text-sm); color: var(--text-secondary); line-height: 1.5; margin-bottom: var(--space-3);">
          ${truncate(proposal.problemStatement || '', 200)}
        </p>
        <div style="display: flex; gap: var(--space-4); font-size: var(--text-xs); color: var(--text-tertiary);">
          <span>💰 $${((proposal.costEstimate?.min || 0) / 1000).toFixed(0)}K - $${((proposal.costEstimate?.max || 0) / 1000).toFixed(0)}K</span>
          <span>📋 ${(proposal.features || []).length} features</span>
          <span>📅 ${(proposal.timeline || []).length} phases</span>
        </div>
      </div>
    `;
  }

  async function renderProposalDetail(container, projectId) {
    const project = await Store.getProject(projectId);
    if (!project || !project.proposal) {
      container.innerHTML = `
        <div class="glass-card-static empty-state">
          <div class="empty-state-icon">📄</div>
          <h3 class="empty-state-title">Proposal Not Found</h3>
          <p class="empty-state-text">This project may not have a generated proposal yet.</p>
          <button class="btn btn-primary" onclick="Router.navigate('proposals')">← Back to Proposals</button>
        </div>
      `;
      return;
    }

    const p = project.proposal;

    container.innerHTML = `
      <div class="page-header">
        <div class="page-header-top">
          <div>
            <h1 class="page-title">${project.company || project.clientName}</h1>
            <p class="page-subtitle">Proposal generated by Pre-Sales Consultant AI</p>
          </div>
          <div class="page-actions">
            <button class="btn btn-ghost" onclick="Router.navigate('proposals')">← Back</button>
            <button class="btn btn-secondary" id="proposal-status-btn">
              ${getStatusEmoji(p.status)} ${capitalizeFirst(p.status || 'draft')}
            </button>
            <button class="btn btn-primary" id="proposal-print">🖨️ Print / PDF</button>
          </div>
        </div>
      </div>

      <div class="glass-card-static proposal-document animate-fade-in-up">
        <!-- Header -->
        <div style="text-align: center; margin-bottom: var(--space-8); padding-bottom: var(--space-6); border-bottom: 1px solid var(--glass-border);">
          <h2 class="text-gradient" style="font-size: var(--text-3xl); margin-bottom: var(--space-2);">Project Proposal</h2>
          <p class="text-secondary">Prepared for <strong>${project.clientName || project.company}</strong></p>
          <p class="text-tertiary" style="font-size: var(--text-sm);">${new Date(p.generatedAt || project.createdAt).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}</p>
        </div>

        <!-- Problem Statement -->
        <div class="proposal-section">
          <h3 class="proposal-section-title">🎯 Problem Understanding</h3>
          <p class="proposal-text">${p.problemStatement}</p>
        </div>

        <!-- Solution Approach -->
        <div class="proposal-section">
          <h3 class="proposal-section-title">💡 Proposed Solution</h3>
          <p class="proposal-text">${p.solution}</p>
        </div>

        <!-- Features -->
        <div class="proposal-section">
          <h3 class="proposal-section-title">📋 Feature Breakdown</h3>
          <div class="table-wrapper" style="margin-top: var(--space-4);">
            <table class="data-table">
              <thead>
                <tr>
                  <th>Feature</th>
                  <th>Priority</th>
                  <th>Complexity</th>
                  <th>Estimate</th>
                </tr>
              </thead>
              <tbody>
                ${(p.features || []).map(f => `
                  <tr>
                    <td>
                      <strong>${f.name}</strong>
                      <div style="font-size: var(--text-xs); color: var(--text-tertiary); margin-top: 4px;">${truncate(f.description || '', 120)}</div>
                    </td>
                    <td><span class="badge ${getPriorityBadge(f.priority)}">${f.priority}</span></td>
                    <td><span class="badge badge-neutral">${f.complexity}</span></td>
                    <td style="white-space: nowrap;">${f.estimate}</td>
                  </tr>
                `).join('')}
              </tbody>
            </table>
          </div>
        </div>

        <!-- Timeline -->
        <div class="proposal-section">
          <h3 class="proposal-section-title">📅 Timeline</h3>
          <div class="proposal-timeline-bar">
            ${(p.timeline || []).map(phase => `
              <div class="proposal-phase" style="background: ${phase.color}22; border: 1px solid ${phase.color}44;">
                <div class="proposal-phase-name" style="color: ${phase.color};">${phase.phase}</div>
                <div class="proposal-phase-duration">${phase.duration}</div>
              </div>
            `).join('')}
          </div>
        </div>

        <!-- Cost Estimate -->
        <div class="proposal-section">
          <h3 class="proposal-section-title">💰 Cost Estimation</h3>
          <div style="display: flex; gap: var(--space-5); margin-top: var(--space-4);">
            <div class="glass-card-static" style="padding: var(--space-5); flex: 1; text-align: center;">
              <div style="font-size: var(--text-sm); color: var(--text-secondary); margin-bottom: var(--space-2);">Estimated Range</div>
              <div style="font-family: var(--font-heading); font-size: var(--text-2xl); font-weight: 800;">
                <span class="text-gradient">$${((p.costEstimate?.min || 0) / 1000).toFixed(0)}K — $${((p.costEstimate?.max || 0) / 1000).toFixed(0)}K</span>
              </div>
              <div style="font-size: var(--text-xs); color: var(--text-tertiary); margin-top: var(--space-2);">
                ${p.costEstimate?.currency || 'USD'} · ~${p.costEstimate?.estimatedHours || 'N/A'} hours
              </div>
            </div>
          </div>
        </div>

        <!-- Value Proposition -->
        <div class="proposal-section">
          <h3 class="proposal-section-title">🏆 Value Proposition</h3>
          <p class="proposal-text">${p.valueProposition}</p>
        </div>

        <!-- Assumptions -->
        <div class="proposal-section">
          <h3 class="proposal-section-title">📌 Assumptions</h3>
          <ul style="padding-left: var(--space-5); display: flex; flex-direction: column; gap: var(--space-2);">
            ${(p.assumptions || []).map(a => `
              <li style="font-size: var(--text-sm); color: var(--text-secondary); list-style: disc;">${a}</li>
            `).join('')}
          </ul>
        </div>
      </div>
    `;

    // Events
    document.getElementById('proposal-print')?.addEventListener('click', () => {
      window.print();
    });

    document.getElementById('proposal-status-btn')?.addEventListener('click', () => {
      showStatusModal(projectId, p.status);
    });
  }

  function showStatusModal(projectId, currentStatus) {
    Modal.show({
      title: 'Update Proposal Status',
      content: `
        <div style="display: flex; flex-direction: column; gap: var(--space-3);">
          ${['draft', 'sent', 'accepted', 'rejected'].map(status => `
            <label style="display: flex; align-items: center; gap: var(--space-3); padding: var(--space-3); border-radius: var(--radius-md); cursor: pointer; transition: background var(--transition-fast);"
                   class="status-option" data-status="${status}"
                   onmouseover="this.style.background='var(--bg-hover)'" onmouseout="this.style.background='transparent'">
              <input type="radio" name="proposal-status" value="${status}" ${status === currentStatus ? 'checked' : ''}
                style="accent-color: var(--accent-cyan);">
              <span>${getStatusEmoji(status)} ${capitalizeFirst(status)}</span>
            </label>
          `).join('')}
        </div>
      `,
      actions: [
        { label: 'Cancel', class: 'btn-secondary', id: 'status-cancel', onClick: () => Modal.close() },
        {
          label: 'Update Status', class: 'btn-primary', id: 'status-save',
          onClick: async () => {
            const selected = document.querySelector('input[name="proposal-status"]:checked')?.value;
            if (selected) {
              const project = await Store.getProject(projectId);
              if (project?.proposal) {
                await Store.updateProject(projectId, {
                  proposal: { ...project.proposal, status: selected },
                  ...(selected === 'accepted' ? { status: 'planning' } : {}),
                });
                await Store.addProjectActivity(projectId, {
                  type: 'proposal',
                  message: `Proposal status changed to "${selected}"`,
                  agent: 'consultant',
                });
                Toast.success(`Proposal status updated to ${selected}`);
                Modal.close();
                renderProposalDetail(document.getElementById('page-content'), projectId);
              }
            }
          },
        },
      ],
    });
  }

  function getStatusEmoji(status) {
    const map = { draft: '📝', sent: '📤', accepted: '✅', rejected: '❌' };
    return map[status] || '📝';
  }

  function getPriorityBadge(priority) {
    const p = (priority || '').toLowerCase();
    if (p === 'critical') return 'badge-danger';
    if (p === 'high') return 'badge-warning';
    if (p === 'medium') return 'badge-info';
    return 'badge-neutral';
  }

  function truncate(str, max) {
    return str.length > max ? str.substring(0, max) + '...' : str;
  }

  return { render };
})();
